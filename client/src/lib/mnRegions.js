/** Ulaanbaatar first, then the aimags in order. */
export const CITIES = [UB, ...Object.keys(AIMAGS)];

export const isCapital = (city) => city === UB;

/** The districts (capital) or sums (aimag) of a city, or [] if unknown. */
export function districtsOf(city) {
  if (isCapital(city)) return Object.keys(UB_DISTRICTS);
  return AIMAGS[city] || [];
}

/** The capital's khoroos as labels ("1-р хороо" …); null for an aimag, whose bags are typed. */
export function khoroosOf(city, district) {
  if (!isCapital(city) || !UB_DISTRICTS[district]) return null;
  return Array.from({ length: UB_DISTRICTS[district] }, (_, i) => `${i + 1}-р хороо`);
}
